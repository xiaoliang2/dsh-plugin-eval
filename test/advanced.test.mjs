// --- lockfile parsing ---

test('package-lock.json is parsed into pinned resolutions with integrity', () => {
  const text = `{
    "name": "x", "version": "1.0.0", "lockfileVersion": 3,
    "packages": {
      "": {"name":"x","version":"1.0.0"},
      "node_modules/lodash": {"version":"4.17.21","integrity":"sha512-abc=="},
      "node_modules/loose": {"version":"^2.0.0"}
    }
  }`
  const r = parseLockfile('package-lock.json', text)
  assert.ok(r.pinned.some((d) => d.name === 'lodash' && d.version === '4.17.21'))
  assert.ok(!r.pinned.some((d) => d.name === 'loose'), 'loose versions are not pinned')
  assert.equal(r.hasIntegrity, true)
})

test('pnpm-lock.yaml is parsed heuristically without a YAML dependency', () => {
  const text = `lockfileVersion: '6.0'
packages:
  /lodash@4.17.21:
    resolution: {integrity: sha512-abc==}
  /semver@7.5.4:
    resolution: {integrity: sha512-def==}
`
  const r = parseLockfile('pnpm-lock.yaml', text)
  assert.equal(r.pinned.length, 2)
  assert.ok(r.pinned.some((d) => d.name === 'lodash' && d.version === '4.17.21'))
  assert.equal(r.hasIntegrity, true)
})

test('yarn.lock v1 is parsed heuristically', () => {
  const text = `# THIS IS AN AUTOGENERATED FILE.
"lodash@^4.17.21":
  version "4.17.21"
  resolved "https://registry.yarnpkg.com/lodash/-/lodash-4.17.21.tgz"
  integrity sha512-abc==

"semver@7.5.4":
  version "7.5.4"
  integrity sha512-def==
`
  const r = parseLockfile('yarn.lock', text)
  assert.equal(r.pinned.length, 2)
  assert.equal(r.hasIntegrity, true)
})

test('auditLockfile on a plugin with a lockfile scores higher than without', async () => {
  const fs = createFsShim(absolute('good-plugin'))
  const { collectLocalSource } = await import('../lib/engine/util.js')
  const src = await collectLocalSource(fs, absolute('good-plugin'))
  const audit = auditLockfile(src)
  assert.equal(audit.present, true)
  assert.ok(audit.files.length >= 2, 'both package-lock.json and pnpm-lock.yaml found')
  assert.equal(audit.signals.hasIntegrity, true)
  assert.ok(audit.score >= 70, `lockfile score high: ${audit.score}`)

  const bare = { texts: {}, files: [] }
  const noLock = auditLockfile(bare)
  assert.equal(noLock.present, false)
  assert.ok(noLock.score < 40)
})

// --- OSV lookup (mocked web) ---

test('queryKnownVulnerabilities reports known CVEs and drops security score', async () => {
  const web = {
    async fetch(req) {
      const url = req.url ?? ''
      if (url.includes('lodash')) {
        return {
          url,
          statusCode: 200,
          body: {
            kind: 'text',
            content: JSON.stringify({
              vulns: [
                { id: 'GHSA-xxxx-xxxx-xxxx', summary: 'Prototype pollution in lodash', aliases: ['CVE-2021-23337'], modified: '2023-01-01T00:00:00Z', published: '2021-01-01T00:00:00Z' },
              ],
            }),
          },
        }
      }
      return { url, statusCode: 200, body: { kind: 'text', content: JSON.stringify({ vulns: [] }) } }
    },
  }
  const r = await queryKnownVulnerabilities({ web }, [
    { name: 'lodash', version: '4.17.21' },
    { name: 'semver', version: '7.5.4' },
  ])
  assert.equal(r.available, true)
  assert.equal(r.checked, 2)
  assert.equal(r.vulns.length, 1)
  assert.equal(r.vulns[0].package, 'lodash')
  assert.ok(r.score < 100, `score penalized: ${r.score}`)
  assert.equal(r.byPackage.lodash, 1)
})

test('queryKnownVulnerabilities degrades without a web service', async () => {
  const r = await queryKnownVulnerabilities({}, [{ name: 'lodash', version: '4.17.21' }])
  assert.equal(r.available, false)
  assert.equal(r.vulns.length, 0)
})

// --- OSV wired into evaluatePlugin ---

test('evaluatePlugin runs OSV + lockfile audit over a fixture', async () => {
  const root = absolute('good-plugin')
  const web = {
    async fetch(req) {
      const url = req.url ?? ''
      if (url.includes('api.osv.dev')) {
        const vulns = url.includes('lodash') ? [{ id: 'GHSA-test', summary: 'test advisory', aliases: ['CVE-TEST'], modified: null, published: null }] : []
        return { url, statusCode: 200, body: { kind: 'text', content: JSON.stringify({ vulns }) } }
      }
      return { url, statusCode: 200, body: { kind: 'text', content: JSON.stringify({ downloads: 0 }) } }
    },
  }
  const r = await evaluatePlugin({
    target: root,
    deps: { fs: createFsShim(root), web },
    runtime: { nodeVersion: '22.0.0', dshVersion: '0.1.0' },
    opts: { allowNetwork: true },
  })
  assert.equal(r.security.osv.available, true)
  assert.ok(r.security.osv.checked >= 2, 'queries manifest + lockfile deps')
  assert.ok(r.security.lockfile.present, true)
  // the known vuln must show up in findings
  assert.ok(r.findings.top.some((f) => /Known vulnerability/.test(f.label)))
})

// --- remote deep scan (mocked web) ---

test('collectRemoteSource scans a GitHub repo without cloning', async () => {
  const web = {
    async fetch(req) {
      const url = req.url ?? ''
      if (url.includes('/git/trees/main')) {
        return {
          url,
          statusCode: 200,
          body: {
            kind: 'text',
            content: JSON.stringify({
              tree: [
                { path: 'package.json', type: 'blob', size: 200 },
                { path: 'src/index.js', type: 'blob', size: 300 },
                { path: 'logo.png', type: 'blob', size: 99999 },
                { path: 'node_modules/x/index.js', type: 'blob', size: 50 },
              ],
            }),
          },
        }
      }
      if (url.includes('api.github.com/repos/demo/good-plugin')) return { url, statusCode: 200, body: { kind: 'text', content: JSON.stringify({ full_name: 'demo/good-plugin', default_branch: 'main' }) } }
      if (url.includes('raw.githubusercontent.com')) {
        const content = url.includes('package.json') ? '{"name":"demo/good-plugin","version":"1.0.0"}' : 'const x = 1'
        return { url, statusCode: 200, body: { kind: 'text', content } }
      }
      return { url, statusCode: 404, body: { kind: 'text', content: '{}' } }
    },
  }
  const r = await collectRemoteSource({ web }, 'demo', 'good-plugin')
  assert.equal(r.kind, 'remote')
  assert.equal(r.defaultBranch, 'main')
  assert.ok(r.files.some((f) => f.path === 'package.json'))
  assert.ok(!r.files.some((f) => f.path === 'logo.png'), 'binaries skipped')
  assert.ok(!r.files.some((f) => f.path.startsWith('node_modules')), 'node_modules skipped')
  assert.equal(r.texts['package.json'], '{"name":"demo/good-plugin","version":"1.0.0"}')
})

test('remote target is deep-scanned end to end', async () => {
  const web = {
    async fetch(req) {
      const url = req.url ?? ''
      if (url.includes('/git/trees/main')) return { url, statusCode: 200, body: { kind: 'text', content: JSON.stringify({ tree: [{ path: 'package.json', type: 'blob', size: 100 }] }) } }
      if (url.includes('api.github.com/repos/demo/plugin')) return { url, statusCode: 200, body: { kind: 'text', content: JSON.stringify({ full_name: 'demo/plugin', default_branch: 'main' }) } }
      if (url.includes('raw.githubusercontent.com')) return { url, statusCode: 200, body: { kind: 'text', content: '{"name":"demo-plugin","version":"1.0.0","license":"MIT"}' } }
      if (url.includes('api.osv.dev')) return { url, statusCode: 200, body: { kind: 'text', content: JSON.stringify({ vulns: [] }) } }
      return { url, statusCode: 200, body: { kind: 'text', content: JSON.stringify({ downloads: 0 }) } }
    },
  }
  const r = await evaluatePlugin({
    target: 'demo/plugin',
    deps: { web },
    runtime: { nodeVersion: '22.0.0', dshVersion: '0.1.0' },
    opts: { allowNetwork: true },
  })
  assert.equal(r.source.kind, 'remote')
  assert.equal(r.manifest.name, 'demo-plugin')
  assert.equal(typeof r.composite.score, 'number')
})

// --- dshVersion runtime resolution ---

test('resolveDshVersion returns explicit value and falls back gracefully', () => {
  assert.equal(resolveDshVersion('9.9.9'), '9.9.9')
  // no explicit value: either the real installed dsh version or undefined — must not throw
  const v = resolveDshVersion(undefined)
  assert.ok(v === undefined || typeof v === 'string')
})

test('compatibility actually verifies DSH peers when dshVersion is known', async () => {
  const root = absolute('good-plugin')
  const r = await evaluatePlugin({
    target: root,
    deps: { fs: createFsShim(root), web: undefined },
    runtime: { nodeVersion: '22.0.0', dshVersion: '0.1.0' },
    opts: { allowNetwork: false },
  })
  // good-plugin declares @deepseek-ai/dsh-tools: "0.1.0" peer, dshVersion 0.1.0 satisfies
  assert.equal(r.compatibility.checks.dshPeersDeclared, true)
  assert.ok(r.compatibility.checks.dshPeers.length >= 1)
  assert.ok(!r.compatibility.findings.some((f) => f.severity === 'high'), 'no high compat findings for a compatible peer')
})
